# start the workflow from saving data to h5 
# but get the system type first
def process_data_into_h5(config):
    molecules_data_folder = config['molecules_path']
    
    if molecules_data_folder == "/path/to/molecules/data":
        raise ValueError("Please set the path for the molecule data path with molecules_path field in config.yml. NOTE: Data must be generated by SPARC DFT library")

    system_type = config['system_type']
    mcsh_max_order = config['mcsh_max_order']
    mcsh_max_r = config['mcsh_max_r']
    functional = config.get('functional', None)

    # match the hdf5 class directory structure
    output_dir = f"./hdf5_molecules_latest_data/{system_type}"
    os.makedirs(output_dir, exist_ok=True)

    systems = os.listdir(molecules_data_folder)

    # process each system
    for system in systems:
        hdf5_writer = HDF5Writer(molecules_data_folder, system_type, system, functional)
        hdf5_writer.process_system(mcsh_max_order, mcsh_max_r)

# discover h5 files after processing
def get_h5_files(mcsh_max_order, mcsh_max_r, system_type):
    output_dir = f"./hdf5_molecules_latest_data/{system_type}"
    h5_pattern = os.path.join(output_dir, f"*_HSMP_*l_{mcsh_max_order}_rcut_{mcsh_max_r:.6f}.h5")
    return glob.glob(h5_pattern)

# data is now processed into h5, discard vacuum environments
def discard_vacuum(h5_output_path, config):
    processor = DiscardVacuum(
        mcsh_max_order=config['mcsh_max_order'],
        mcsh_step_size=config['mcsh_step_size'],
        mcsh_max_r=config['mcsh_max_r']
    )
    
    # Get all HDF5 files in the output directory
    h5_files = get_h5_files(h5_output_path, config['mcsh_max_order'], config['mcsh_max_r'])
    
    if not h5_files:
        print("No HDF5 files found to process!")
        return
    
    # Process each file
    for h5_path in h5_files:
        print(f"Processing vacuum removal for: {os.path.basename(h5_path)}")
        processor.process_system(h5_path)

# run sub-sampling process
def run_subsampling(self, systems):
        for system in systems:
            hdf5_path = os.path.join(
                self.base_dir,
                f"{system}_HSMP_{self.config['mcsh_max_order']}l_"
                f"{self.config['mcsh_max_r']:.6f}.h5"
            )
            subsampler = SystemSubsampler(
                system_path=hdf5_path,
                cutoff_sig=self.config['cutoff_sig'],
                mcsh_max_order=self.config['mcsh_max_order'],
                mcsh_step_size=self.config['mcsh_step_size'],
                mcsh_max_r=self.config['mcsh_max_r'],
                verbose=True
            )
            subsampler.run()


# run partitioning scheme 
def run_partitioning(config):
    output_dir = f"partitioned_data/{config['system_type']}"
    os.makedirs(output_dir, exist_ok=True)
    
    # Get all H5 files
    h5_files = get_h5_files(config['mcsh_max_order'], config['mcsh_max_r'], config['system_type'])
    
    if not h5_files:
        print("No HDF5 files found for partitioning!")
        return
        
    # Initialize partitioner
    partitioner = Partitioner(config)
    
    # Run partitioning
    refdata_path = config['reference_data_path']
    if not os.path.exists(refdata_path):
        raise ValueError(f"Reference data not found at: {refdata_path}")
        
    partitioner.run_partitioning(h5_files, refdata_path, output_dir)
    print(f"Partitioning complete. Results saved to: {output_dir}")


